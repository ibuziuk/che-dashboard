import { api } from '@eclipse-che/common';
import { FastifyInstance, FastifyReply, FastifyRequest } from 'fastify';

import { baseApiPath } from '@/constants/config';
import {
  namespacedSandboxSchema,
  namespacedSchema,
  sandboxBodySchema,
  sandboxPatchSchema,
} from '@/constants/schemas';
import { restParams } from '@/models';
import { getDevWorkspaceClient } from '@/routes/api/helpers/getDevWorkspaceClient';
import { getToken } from '@/routes/api/helpers/getToken';
import { getSchema } from '@/services/helpers';

const tags = ['Sandbox'];

// Generated by Claude Opus 5
export function registerSandboxRoutes(instance: FastifyInstance) {
  instance.register(async server => {
    server.get(
      `${baseApiPath}/namespace/:namespace/sandboxes`,
      getSchema({
        tags,
        params: namespacedSchema,
      }),
      async function (request: FastifyRequest) {
        const { namespace } = request.params as restParams.INamespacedParams;
        const token = getToken(request);
        const { sandboxApi } = getDevWorkspaceClient(token);
        return sandboxApi.listInNamespace(namespace);
      },
    );

    server.get(
      `${baseApiPath}/namespace/:namespace/sandboxes/:sandboxName`,
      getSchema({
        tags,
        params: namespacedSandboxSchema,
      }),
      async function (request: FastifyRequest) {
        const { namespace, sandboxName } = request.params as restParams.INamespacedSandboxParams;
        const token = getToken(request);
        const { sandboxApi } = getDevWorkspaceClient(token);
        return sandboxApi.getByName(namespace, sandboxName);
      },
    );

    server.post(
      `${baseApiPath}/namespace/:namespace/sandboxes`,
      getSchema({
        tags,
        params: namespacedSchema,
        body: sandboxBodySchema,
      }),
      async function (request: FastifyRequest) {
        const { namespace } = request.params as restParams.INamespacedParams;
        const sandbox = request.body as api.ISandbox;
        const token = getToken(request);
        const { sandboxApi } = getDevWorkspaceClient(token);
        return sandboxApi.create(namespace, sandbox);
      },
    );

    server.patch(
      `${baseApiPath}/namespace/:namespace/sandboxes/:sandboxName`,
      getSchema({
        tags,
        params: namespacedSandboxSchema,
        body: sandboxPatchSchema,
      }),
      async function (request: FastifyRequest) {
        const { namespace, sandboxName } = request.params as restParams.INamespacedSandboxParams;
        const patches = request.body as api.IPatch[];
        const token = getToken(request);
        const { sandboxApi } = getDevWorkspaceClient(token);
        return sandboxApi.patch(namespace, sandboxName, patches);
      },
    );

    server.delete(
      `${baseApiPath}/namespace/:namespace/sandboxes/:sandboxName`,
      getSchema({
        tags,
        params: namespacedSandboxSchema,
        response: {
          204: {
            description: 'The Sandbox successfully deleted',
            type: 'null',
          },
        },
      }),
      async function (request: FastifyRequest, reply: FastifyReply) {
        const { namespace, sandboxName } = request.params as restParams.INamespacedSandboxParams;
        const token = getToken(request);
        const { sandboxApi } = getDevWorkspaceClient(token);

        await sandboxApi.delete(namespace, sandboxName);

        reply.code(204).send();
      },
    );
  });
}
