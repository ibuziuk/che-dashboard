import { api } from '@eclipse-che/common';
import { KubeConfig } from '@kubernetes/client-node';

import {
  SANDBOX_API_VERSION,
  SANDBOX_GROUP,
  SANDBOX_KIND,
  SANDBOX_PLURAL,
  SANDBOX_VERSION,
} from '@/constants/k8s';
import { createError } from '@/devworkspaceClient/services/helpers/createError';
import {
  CustomObjectAPI,
  prepareCustomObjectAPI,
} from '@/devworkspaceClient/services/helpers/prepareCustomObjectAPI';
import { ISandboxApi } from '@/devworkspaceClient/types';

const SANDBOX_API_ERROR_LABEL = 'CUSTOM_OBJECTS_API_ERROR';

// Generated by Claude Opus 5
export class SandboxApiService implements ISandboxApi {
  private readonly customObjectAPI: CustomObjectAPI;

  constructor(kc: KubeConfig) {
    this.customObjectAPI = prepareCustomObjectAPI(kc);
  }

  async listInNamespace(namespace: string): Promise<api.ISandboxList> {
    try {
      const resp = await this.customObjectAPI.listNamespacedCustomObject({
        group: SANDBOX_GROUP,
        version: SANDBOX_VERSION,
        namespace,
        plural: SANDBOX_PLURAL,
      });
      const list = resp as api.ISandboxList;
      return {
        apiVersion: list.apiVersion,
        kind: list.kind,
        metadata: list.metadata,
        items: list.items || [],
      };
    } catch (e) {
      throw createError(e, SANDBOX_API_ERROR_LABEL, 'Unable to list sandboxes');
    }
  }

  async getByName(namespace: string, name: string): Promise<api.ISandbox> {
    try {
      const resp = await this.customObjectAPI.getNamespacedCustomObject({
        group: SANDBOX_GROUP,
        version: SANDBOX_VERSION,
        namespace,
        plural: SANDBOX_PLURAL,
        name,
      });
      return resp as api.ISandbox;
    } catch (e) {
      throw createError(e, SANDBOX_API_ERROR_LABEL, `Unable to get sandbox "${namespace}/${name}"`);
    }
  }

  async create(namespace: string, sandbox: api.ISandbox): Promise<api.ISandbox> {
    const body: api.ISandbox = {
      ...sandbox,
      apiVersion: SANDBOX_API_VERSION,
      kind: SANDBOX_KIND,
      metadata: {
        ...sandbox.metadata,
        namespace,
      },
    };
    try {
      const resp = await this.customObjectAPI.createNamespacedCustomObject({
        group: SANDBOX_GROUP,
        version: SANDBOX_VERSION,
        namespace,
        plural: SANDBOX_PLURAL,
        body,
      });
      return resp as api.ISandbox;
    } catch (e) {
      throw createError(e, SANDBOX_API_ERROR_LABEL, 'Unable to create sandbox');
    }
  }

  async patch(namespace: string, name: string, patches: api.IPatch[]): Promise<api.ISandbox> {
    try {
      const resp = await this.customObjectAPI.patchNamespacedCustomObject({
        group: SANDBOX_GROUP,
        version: SANDBOX_VERSION,
        namespace,
        plural: SANDBOX_PLURAL,
        name,
        body: patches,
      });
      return resp as api.ISandbox;
    } catch (e) {
      throw createError(
        e,
        SANDBOX_API_ERROR_LABEL,
        `Unable to patch sandbox "${namespace}/${name}"`,
      );
    }
  }

  async delete(namespace: string, name: string): Promise<void> {
    try {
      await this.customObjectAPI.deleteNamespacedCustomObject({
        group: SANDBOX_GROUP,
        version: SANDBOX_VERSION,
        namespace,
        plural: SANDBOX_PLURAL,
        name,
      });
    } catch (e) {
      throw createError(
        e,
        SANDBOX_API_ERROR_LABEL,
        `Unable to delete sandbox "${namespace}/${name}"`,
      );
    }
  }
}
