import { api } from '@eclipse-che/common';

/**
 * Condition types reported by the Sandbox controller.
 * @see https://agent-sandbox.sigs.k8s.io/
 */
export const SANDBOX_CONDITION_READY = 'Ready';
export const SANDBOX_CONDITION_SUSPENDED = 'Suspended';
export const SANDBOX_CONDITION_POD_SCHEDULED = 'PodScheduled';
export const SANDBOX_CONDITION_FINISHED = 'Finished';

/**
 * Lifecycle actions offered for a Sandbox.
 *
 * The CRD exposes a single `spec.operatingMode` field with two values, so
 * `Start` and `Resume` are synonyms, and so are `Stop` and `Hibernate`.
 */
export enum SandboxAction {
  START = 'Start',
  RESUME = 'Resume',
  STOP = 'Stop',
  HIBERNATE = 'Hibernate',
  DELETE = 'Delete',
}

/** Phases in which the Sandbox is expected to keep changing on its own. */
const TRANSITIONAL_PHASES: ReadonlyArray<api.SandboxPhase> = [
  api.SandboxPhase.STARTING,
  api.SandboxPhase.STOPPING,
  api.SandboxPhase.TERMINATING,
  api.SandboxPhase.UNKNOWN,
];

export function getSandboxName(sandbox: api.ISandbox): string {
  return sandbox.metadata?.name || '';
}

export function getSandboxCondition(
  sandbox: api.ISandbox,
  type: string,
): api.ISandboxCondition | undefined {
  return sandbox.status?.conditions?.find(condition => condition.type === type);
}

/**
 * Derives the display phase of a Sandbox from its spec and its status conditions.
 *
 * The CRD reports readiness rather than a phase, so the richer set of states shown
 * in the UI is computed here.
 */
// Generated by Claude Opus 5
export function getSandboxPhase(sandbox: api.ISandbox): api.SandboxPhase {
  if (sandbox.metadata?.deletionTimestamp !== undefined) {
    return api.SandboxPhase.TERMINATING;
  }

  const suspendedCondition = getSandboxCondition(sandbox, SANDBOX_CONDITION_SUSPENDED);

  if (sandbox.spec?.operatingMode === 'Suspended') {
    // The Pod is torn down asynchronously, so the Sandbox is only hibernated
    // once the controller confirms it.
    return suspendedCondition?.status === 'True'
      ? api.SandboxPhase.HIBERNATED
      : api.SandboxPhase.STOPPING;
  }

  const finishedCondition = getSandboxCondition(sandbox, SANDBOX_CONDITION_FINISHED);
  if (finishedCondition?.status === 'True') {
    return finishedCondition.reason === 'PodFailed'
      ? api.SandboxPhase.FAILED
      : api.SandboxPhase.STOPPED;
  }

  const readyCondition = getSandboxCondition(sandbox, SANDBOX_CONDITION_READY);
  if (readyCondition?.status === 'True') {
    return api.SandboxPhase.RUNNING;
  }

  const podScheduledCondition = getSandboxCondition(sandbox, SANDBOX_CONDITION_POD_SCHEDULED);
  if (podScheduledCondition?.status === 'False') {
    // Unschedulable or scheduling-gated.
    return api.SandboxPhase.BLOCKED;
  }

  if (readyCondition?.status === 'False') {
    switch (readyCondition.reason) {
      case 'SandboxExpired':
        return api.SandboxPhase.STOPPED;
      case 'InvalidConfiguration':
      case 'MultiplePods':
        return api.SandboxPhase.FAILED;
      default:
        return api.SandboxPhase.STARTING;
    }
  }

  if (sandbox.status?.conditions === undefined || sandbox.status.conditions.length === 0) {
    // The controller has not reconciled the Sandbox yet.
    return api.SandboxPhase.STARTING;
  }

  return api.SandboxPhase.UNKNOWN;
}

/**
 * Returns true when the Sandbox is running or is expected to change state on its own,
 * i.e. when its status is worth polling.
 */
export function isSandboxTransitioning(sandbox: api.ISandbox): boolean {
  const phase = getSandboxPhase(sandbox);
  return phase === api.SandboxPhase.RUNNING || TRANSITIONAL_PHASES.includes(phase);
}

/**
 * Returns the lifecycle actions applicable to the given Sandbox, `Delete` excluded.
 */
export function getSandboxLifecycleActions(sandbox: api.ISandbox): SandboxAction[] {
  switch (getSandboxPhase(sandbox)) {
    case api.SandboxPhase.RUNNING:
    case api.SandboxPhase.STARTING:
    case api.SandboxPhase.BLOCKED:
      return [SandboxAction.STOP];
    case api.SandboxPhase.HIBERNATED:
      return [SandboxAction.RESUME];
    case api.SandboxPhase.STOPPED:
    case api.SandboxPhase.FAILED:
      return [SandboxAction.START];
    default:
      // Stopping, Terminating and Unknown offer no lifecycle action.
      return [];
  }
}

/**
 * Maps a lifecycle action onto the operating mode it requests.
 * Returns `undefined` for actions that are not operating-mode transitions.
 */
export function getOperatingModeForAction(
  action: SandboxAction,
): api.SandboxOperatingMode | undefined {
  switch (action) {
    case SandboxAction.START:
    case SandboxAction.RESUME:
      return 'Running';
    case SandboxAction.STOP:
    case SandboxAction.HIBERNATE:
      return 'Suspended';
    default:
      return undefined;
  }
}

/**
 * Builds the JSON patch that switches a Sandbox to the given operating mode.
 *
 * `add` is used rather than `replace` so that the patch also succeeds on a Sandbox
 * that does not carry an explicit `spec.operatingMode` yet.
 */
export function buildOperatingModePatch(operatingMode: api.SandboxOperatingMode): api.IPatch[] {
  return [
    {
      op: 'add',
      path: '/spec/operatingMode',
      value: operatingMode,
    },
  ];
}

/**
 * Returns the conditions that describe a problem, so the UI can surface the reason
 * a Sandbox is not running.
 */
export function getSandboxErrorConditions(sandbox: api.ISandbox): api.ISandboxCondition[] {
  const phase = getSandboxPhase(sandbox);
  if (phase !== api.SandboxPhase.FAILED && phase !== api.SandboxPhase.BLOCKED) {
    return [];
  }
  return (sandbox.status?.conditions || []).filter(
    condition =>
      (condition.type === SANDBOX_CONDITION_READY ||
        condition.type === SANDBOX_CONDITION_POD_SCHEDULED) &&
      condition.status === 'False',
  );
}

/**
 * Returns a single human readable failure message, or `undefined` when the Sandbox is healthy.
 */
export function getSandboxErrorMessage(sandbox: api.ISandbox): string | undefined {
  const conditions = getSandboxErrorConditions(sandbox);
  if (conditions.length === 0) {
    return undefined;
  }
  const message = conditions
    .map(condition => condition.message || condition.reason)
    .filter(text => text !== undefined && text !== '')
    .join('; ');
  return message === '' ? undefined : message;
}
