import { api } from '@eclipse-che/common';
import { Label, LabelProps } from '@patternfly/react-core';
import {
  CheckCircleIcon,
  ExclamationCircleIcon,
  ExclamationTriangleIcon,
  InProgressIcon,
  MoonIcon,
  OffIcon,
  UnknownIcon,
} from '@patternfly/react-icons';
import React from 'react';

import { CheTooltip } from '@/components/CheTooltip';
import { getSandboxErrorMessage, getSandboxPhase } from '@/services/sandbox';

type LabelStyle = {
  color: LabelProps['color'];
  icon: React.ReactElement;
};

// Generated by Claude Opus 5
const STYLE_BY_PHASE: Record<api.SandboxPhase, LabelStyle> = {
  [api.SandboxPhase.RUNNING]: { color: 'green', icon: <CheckCircleIcon /> },
  [api.SandboxPhase.STARTING]: { color: 'blue', icon: <InProgressIcon /> },
  [api.SandboxPhase.STOPPING]: { color: 'blue', icon: <InProgressIcon /> },
  [api.SandboxPhase.TERMINATING]: { color: 'grey', icon: <InProgressIcon /> },
  [api.SandboxPhase.HIBERNATED]: { color: 'purple', icon: <MoonIcon /> },
  [api.SandboxPhase.STOPPED]: { color: 'grey', icon: <OffIcon /> },
  [api.SandboxPhase.BLOCKED]: { color: 'orange', icon: <ExclamationTriangleIcon /> },
  [api.SandboxPhase.FAILED]: { color: 'red', icon: <ExclamationCircleIcon /> },
  [api.SandboxPhase.UNKNOWN]: { color: 'grey', icon: <UnknownIcon /> },
};

export type Props = {
  sandbox: api.ISandbox;
};

export class SandboxStatusLabel extends React.PureComponent<Props> {
  public render(): React.ReactElement {
    const { sandbox } = this.props;

    const phase = getSandboxPhase(sandbox);
    const { color, icon } = STYLE_BY_PHASE[phase];
    const errorMessage = getSandboxErrorMessage(sandbox);

    const label = (
      <Label color={color} icon={icon} data-testid="sandbox-status-label">
        {phase}
      </Label>
    );

    if (errorMessage === undefined) {
      return label;
    }

    return <CheTooltip content={errorMessage}>{label}</CheTooltip>;
  }
}
