import { api } from '@eclipse-che/common';
import {
  ActionGroup,
  Alert,
  AlertVariant,
  Button,
  ButtonVariant,
  Content,
  Divider,
  Form,
  FormGroup,
  FormHelperText,
  HelperText,
  HelperTextItem,
  PageSection,
  PageSectionVariants,
  TextInput,
  ValidatedOptions,
} from '@patternfly/react-core';
import { cloneDeep } from 'lodash';
import React from 'react';

import Head from '@/components/Head';
import { SandboxSamplesGallery } from '@/pages/AgentSpace/SamplesGallery';
import { generateSuffix } from '@/services/helpers/generateName';
import { getSandboxSampleById, ISandboxSample } from '@/services/sandbox/samples';

const NAME_MAX_LENGTH = 63;
/** RFC 1123 label, as required by the Kubernetes API for an object name. */
const NAME_PATTERN = /^[a-z0-9]([-a-z0-9]*[a-z0-9])?$/;
/** RFC 1123 subdomain, as required for a RuntimeClass name. */
const RUNTIME_CLASS_PATTERN = /^[a-z0-9]([-a-z0-9.]*[a-z0-9])?$/;
const CPU_PATTERN = /^\d+(\.\d+)?m?$/;
const MEMORY_PATTERN = /^\d+(\.\d+)?(Ei|Pi|Ti|Gi|Mi|Ki|E|P|T|G|M|k)?$/;

const ERROR_NAME_EMPTY = 'The name cannot be empty.';
const ERROR_NAME_MAX_LENGTH = `The name cannot be longer than ${NAME_MAX_LENGTH} characters.`;
const ERROR_NAME_PATTERN =
  'The name can contain only lowercase letters, digits and dashes. It must start and end with a letter or a digit.';
const ERROR_NAME_EXISTS = 'A sandbox with this name already exists.';
const ERROR_IMAGE_EMPTY = 'The container image cannot be empty.';
const ERROR_RUNTIME_CLASS_PATTERN =
  'The runtime class can contain only lowercase letters, digits, dashes and dots.';
const ERROR_CPU_PATTERN =
  'The CPU limit must be a number of cores, e.g. "2", or millicores, e.g. "500m".';
const ERROR_MEMORY_PATTERN =
  'The memory limit must be a quantity, e.g. "512Mi", "2Gi" or "1000000".';

const DEFAULT_CONTAINER_NAME = 'main';
const DEFAULT_IMAGE = 'registry.access.redhat.com/ubi9/ubi-minimal:latest';
const DEFAULT_CPU_LIMIT = '500m';
const DEFAULT_MEMORY_LIMIT = '512Mi';

export type Props = {
  error: string | undefined;
  isLoading: boolean;
  existingNames: string[];
  /** Identifier of the sample preselected through the URL, if any. */
  sampleId: string | undefined;
  onCancel: () => void;
  onCreate: (sandbox: api.ISandbox) => void;
};

export type State = {
  cpuLimit: string;
  image: string;
  memoryLimit: string;
  name: string;
  runtimeClassName: string;
  sampleId: string | undefined;
};

/**
 * Form that builds a new Sandbox custom resource.
 *
 * The container image, the runtime class and the resource limits are the only parts of
 * the pod template exposed here; everything else is inherited from the selected sample.
 */
// Generated by Claude Opus 5
export class AgentSpaceCreate extends React.PureComponent<Props, State> {
  constructor(props: Props) {
    super(props);

    this.state = AgentSpaceCreate.buildStateFromSample(getSandboxSampleById(props.sampleId || ''));
  }

  private static buildStateFromSample(sample: ISandboxSample | undefined): State {
    const container = sample?.spec.podTemplate.spec.containers[0];
    const limits = container?.resources?.limits;

    return {
      cpuLimit: limits?.cpu || DEFAULT_CPU_LIMIT,
      image: container?.image || DEFAULT_IMAGE,
      memoryLimit: limits?.memory || DEFAULT_MEMORY_LIMIT,
      name: (sample?.id || 'sandbox') + generateSuffix(),
      runtimeClassName: sample?.spec.podTemplate.spec.runtimeClassName || '',
      sampleId: sample?.id,
    };
  }

  private handleSampleClick(sample: ISandboxSample): void {
    this.setState(AgentSpaceCreate.buildStateFromSample(sample));
  }

  private get nameError(): string | undefined {
    const name = this.state.name.trim();
    if (name.length === 0) {
      return ERROR_NAME_EMPTY;
    }
    if (name.length > NAME_MAX_LENGTH) {
      return ERROR_NAME_MAX_LENGTH;
    }
    if (NAME_PATTERN.test(name) === false) {
      return ERROR_NAME_PATTERN;
    }
    if (this.props.existingNames.includes(name)) {
      return ERROR_NAME_EXISTS;
    }
    return undefined;
  }

  private get imageError(): string | undefined {
    return this.state.image.trim().length === 0 ? ERROR_IMAGE_EMPTY : undefined;
  }

  private get runtimeClassError(): string | undefined {
    const runtimeClassName = this.state.runtimeClassName.trim();
    if (runtimeClassName.length === 0) {
      return undefined;
    }
    return RUNTIME_CLASS_PATTERN.test(runtimeClassName) ? undefined : ERROR_RUNTIME_CLASS_PATTERN;
  }

  private get cpuLimitError(): string | undefined {
    const cpuLimit = this.state.cpuLimit.trim();
    if (cpuLimit.length === 0) {
      return undefined;
    }
    return CPU_PATTERN.test(cpuLimit) ? undefined : ERROR_CPU_PATTERN;
  }

  private get memoryLimitError(): string | undefined {
    const memoryLimit = this.state.memoryLimit.trim();
    if (memoryLimit.length === 0) {
      return undefined;
    }
    return MEMORY_PATTERN.test(memoryLimit) ? undefined : ERROR_MEMORY_PATTERN;
  }

  private get isValid(): boolean {
    return (
      this.nameError === undefined &&
      this.imageError === undefined &&
      this.runtimeClassError === undefined &&
      this.cpuLimitError === undefined &&
      this.memoryLimitError === undefined
    );
  }

  private buildSandbox(): api.ISandbox {
    const { cpuLimit, image, memoryLimit, name, runtimeClassName, sampleId } = this.state;

    const sample = getSandboxSampleById(sampleId || '');
    const spec: api.ISandboxSpec = sample
      ? cloneDeep(sample.spec)
      : {
          podTemplate: {
            spec: {
              containers: [
                {
                  name: DEFAULT_CONTAINER_NAME,
                  image: image.trim(),
                  command: ['/bin/sh', '-c', 'sleep infinity'],
                },
              ],
            },
          },
        };

    const container = spec.podTemplate.spec.containers[0];
    container.image = image.trim();

    const limits: { [key: string]: string } = {};
    if (cpuLimit.trim().length > 0) {
      limits.cpu = cpuLimit.trim();
    }
    if (memoryLimit.trim().length > 0) {
      limits.memory = memoryLimit.trim();
    }
    // Requests from the sample are dropped so that they can never end up above the
    // limits entered here. Kubernetes then defaults the requests to the limits.
    container.resources = Object.keys(limits).length > 0 ? { limits } : undefined;

    if (runtimeClassName.trim().length > 0) {
      spec.podTemplate.spec.runtimeClassName = runtimeClassName.trim();
    } else {
      delete spec.podTemplate.spec.runtimeClassName;
    }

    return {
      metadata: {
        name: name.trim(),
      },
      spec,
    };
  }

  private handleSubmit(event: React.FormEvent): void {
    event.preventDefault();

    if (this.isValid === false) {
      return;
    }

    this.props.onCreate(this.buildSandbox());
  }

  private renderTextInput(
    id: string,
    label: string,
    value: string,
    error: string | undefined,
    isRequired: boolean,
    placeholder: string,
    onChange: (value: string) => void,
    helperText?: string,
  ): React.ReactElement {
    const validated = error === undefined ? ValidatedOptions.default : ValidatedOptions.error;

    return (
      <FormGroup label={label} fieldId={id} isRequired={isRequired}>
        <TextInput
          id={id}
          name={id}
          data-testid={id}
          value={value}
          placeholder={placeholder}
          validated={validated}
          onChange={(_event, newValue) => onChange(newValue)}
        />
        {(error !== undefined || helperText !== undefined) && (
          <FormHelperText>
            <HelperText>
              <HelperTextItem
                variant={error === undefined ? 'default' : 'error'}
                data-testid={`${id}-helper-text`}
              >
                {error !== undefined ? error : helperText}
              </HelperTextItem>
            </HelperText>
          </FormHelperText>
        )}
      </FormGroup>
    );
  }

  public render(): React.ReactElement {
    const { error, isLoading, onCancel } = this.props;
    const { cpuLimit, image, memoryLimit, name, runtimeClassName, sampleId } = this.state;

    return (
      <React.Fragment>
        <Head pageName="Create Sandbox" />
        <PageSection variant={PageSectionVariants.default}>
          <Content>
            <Content component="h1">Create Sandbox</Content>
            <Content component="p">
              Start from one of the samples, then adjust the name, the runtime class and the
              resource limits.
            </Content>
          </Content>
        </PageSection>
        <Divider component="div" />
        <PageSection variant={PageSectionVariants.default}>
          <Content>
            <Content component="h2">Getting Started</Content>
          </Content>
          <SandboxSamplesGallery
            selectedSampleId={sampleId}
            onSampleClick={sample => this.handleSampleClick(sample)}
          />
        </PageSection>
        <PageSection variant={PageSectionVariants.default}>
          {error !== undefined && (
            <Alert
              variant={AlertVariant.danger}
              isInline
              title="Failed to create the sandbox"
              data-testid="create-sandbox-error"
            >
              {error}
            </Alert>
          )}
          <Form onSubmit={event => this.handleSubmit(event)} data-testid="create-sandbox-form">
            {this.renderTextInput(
              'sandbox-name',
              'Name',
              name,
              this.nameError,
              true,
              'my-sandbox',
              value => this.setState({ name: value }),
            )}
            {this.renderTextInput(
              'sandbox-image',
              'Container image',
              image,
              this.imageError,
              true,
              DEFAULT_IMAGE,
              value => this.setState({ image: value }),
            )}
            {this.renderTextInput(
              'sandbox-runtime-class',
              'Runtime class',
              runtimeClassName,
              this.runtimeClassError,
              false,
              'gvisor',
              value => this.setState({ runtimeClassName: value }),
              'Optional. The RuntimeClass used to isolate the sandbox pod, e.g. gvisor or kata.',
            )}
            {this.renderTextInput(
              'sandbox-cpu-limit',
              'CPU limit',
              cpuLimit,
              this.cpuLimitError,
              false,
              DEFAULT_CPU_LIMIT,
              value => this.setState({ cpuLimit: value }),
              'Number of cores, e.g. 2, or millicores, e.g. 500m.',
            )}
            {this.renderTextInput(
              'sandbox-memory-limit',
              'Memory limit',
              memoryLimit,
              this.memoryLimitError,
              false,
              DEFAULT_MEMORY_LIMIT,
              value => this.setState({ memoryLimit: value }),
              'A Kubernetes quantity, e.g. 512Mi or 2Gi.',
            )}
            <ActionGroup>
              <Button
                type="submit"
                variant={ButtonVariant.primary}
                isDisabled={this.isValid === false || isLoading}
                isLoading={isLoading}
                data-testid="submit-sandbox-button"
              >
                Create
              </Button>
              <Button
                variant={ButtonVariant.link}
                onClick={() => onCancel()}
                data-testid="cancel-sandbox-button"
              >
                Cancel
              </Button>
            </ActionGroup>
          </Form>
        </PageSection>
      </React.Fragment>
    );
  }
}

export default AgentSpaceCreate;
